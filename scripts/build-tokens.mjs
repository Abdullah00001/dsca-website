#!/usr/bin/env node

import { existsSync, mkdirSync, watch } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = resolve(__dirname, '..');

const isWatchMode = process.argv.includes('--watch');

/**
 * Configure paths & sources according to DTCG 3-tier architecture:
 * 1. Primitives (Foundation scales)
 * 2. Semantics (Intent-based tokens with light & dark theme variants)
 * 3. Components (Component-scoped bindings)
 */
const baseTokensSource = [
  'tokens/01-primitive/**/*.tokens.json',
  'tokens/02-semantic/color-light.tokens.json',
  'tokens/02-semantic/elevation.tokens.json',
  'tokens/03-component/**/*.tokens.json',
];

const darkTokensSource = [
  'tokens/01-primitive/**/*.tokens.json',
  'tokens/02-semantic/color-dark.tokens.json',
  'tokens/02-semantic/elevation.tokens.json',
  'tokens/03-component/**/*.tokens.json',
];

/**
 * Recursively extracts values from token objects.
 */
function extractNestedValues(obj) {
  if (obj && typeof obj === 'object') {
    if ('$value' in obj || 'value' in obj) {
      return obj.$value ?? obj.value;
    }
    const result = {};
    for (const [key, val] of Object.entries(obj)) {
      result[key] = extractNestedValues(val);
    }
    return result;
  }
  return obj;
}

/**
 * Custom format for pure TypeScript: generates strongly-typed constants and
 * nested object with `as const`, completely eliminating .js or .d.ts files.
 */
const typescriptPureFormat = ({ dictionary }) => {
  const lines = [
    '/**',
    ' * Do not edit directly; this file was auto-generated by Style Dictionary.',
    ' */\n',
  ];

  for (const token of dictionary.allTokens) {
    const desc = token.$description || token.comment;
    if (desc) lines.push(`/** ${desc} */`);
    lines.push(`export const ${token.name} = ${JSON.stringify(token.$value)} as const;`);
  }

  const nested = extractNestedValues(dictionary.tokens);
  lines.push(`\nexport const tokens = ${JSON.stringify(nested, null, 2)} as const;\n`);
  lines.push('export type Tokens = typeof tokens;');
  lines.push('export default tokens;\n');

  return lines.join('\n');
};

/**
 * Helper to ensure destination directory exists before build.
 */
function ensureDirectories() {
  const dirs = [
    resolve(rootDir, 'src/styles'),
    resolve(rootDir, 'src/tokens'),
  ];
  for (const dir of dirs) {
    if (!existsSync(dir)) {
      mkdirSync(dir, { recursive: true });
    }
  }
}

/**
 * Execute Style Dictionary builds for all themes and platforms.
 */
async function buildTokens() {
  const startTime = performance.now();
  console.log('🎨 Building design tokens with Style Dictionary...');

  ensureDirectories();

  // 1. Build Base / Light Tokens (CSS variables & Pure TypeScript index.ts)
  const sdBase = new StyleDictionary({
    source: baseTokensSource,
    hooks: {
      formats: {
        'typescript/pure': typescriptPureFormat,
      },
    },
    platforms: {
      css: {
        transformGroup: 'css',
        buildPath: 'src/styles/',
        files: [
          {
            destination: 'tokens.css',
            format: 'css/variables',
            options: {
              outputReferences: true,
            },
          },
        ],
      },
      ts: {
        transformGroup: 'js',
        buildPath: 'src/tokens/',
        files: [
          {
            destination: 'index.ts',
            format: 'typescript/pure',
          },
        ],
      },
    },
  });

  await sdBase.buildAllPlatforms();

  // 2. Build Dark Mode Semantic Tokens (CSS variables targeted to [data-theme="dark"] and .dark)
  const sdDark = new StyleDictionary({
    log: {
      warnings: 'disabled', // suppresses warning about cross-file references to base tokens.css
    },
    source: darkTokensSource,
    platforms: {
      css: {
        transformGroup: 'css',
        buildPath: 'src/styles/',
        files: [
          {
            destination: 'tokens-dark.css',
            format: 'css/variables',
            filter: (token) => token.filePath.includes('color-dark'),
            options: {
              selector: ':root[data-theme="dark"], .dark',
              outputReferences: true,
            },
          },
        ],
      },
    },
  });

  await sdDark.buildAllPlatforms();

  const duration = (performance.now() - startTime).toFixed(1);
  console.log(`✨ Design tokens successfully built in ${duration}ms!`);
}

// Initial build
await buildTokens();

// Watch mode support
if (isWatchMode) {
  const tokensDir = resolve(rootDir, 'tokens');
  console.log(`👀 Watching for token changes in ${tokensDir}...`);

  let debounceTimer = null;
  watch(tokensDir, { recursive: true }, (_eventType, filename) => {
    if (filename && filename.endsWith('.json')) {
      if (debounceTimer) clearTimeout(debounceTimer);
      debounceTimer = setTimeout(async () => {
        console.log(`\n🔄 Token file changed (${filename}), rebuilding...`);
        try {
          await buildTokens();
        } catch (err) {
          console.error('❌ Build failed:', err);
        }
      }, 150);
    }
  });
}
