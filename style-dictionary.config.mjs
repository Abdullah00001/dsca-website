function extractNestedValues(obj) {
  if (obj && typeof obj === 'object') {
    if ('$value' in obj || 'value' in obj) {
      return obj.$value ?? obj.value;
    }
    const result = {};
    for (const [key, val] of Object.entries(obj)) {
      result[key] = extractNestedValues(val);
    }
    return result;
  }
  return obj;
}

